// All I/O delays are simulated; this measures the cost of waiting for redundant
// metadata operations, not a real service SLA or an audio frame.
func TestFirstConfirmedMetadataLatencyMeasurement(t *testing.T) {
	track := Track{Title: "Song", Artist: "Artist", Artists: []string{"Artist"}, Album: "Album", Duration: 210 * time.Second}
	first := Candidate{ID: "abcdefghijk", Title: "Song", Channel: "Artist", Verified: true, Duration: 210}
	second := first
	second.ID, second.Track, second.Album = "lmnopqrstuv", "Song", "Album"
	second.Artists = []string{"Artist"}
	second.Description = "Auto-generated by YouTube."
	searches, checks := 0, 0
	start := time.Now()
	got, err := discoverSpotify(context.Background(), track, DefaultMatchPolicy(), "query", func(string, string) ([]*Candidate, error) {
		searches++
		time.Sleep(10 * time.Millisecond)
		return []*Candidate{&first, &second}, nil
	}, func(c Candidate) (Candidate, error) { checks++; time.Sleep(10 * time.Millisecond); return c, nil })
	t.Logf("selected=%s searches=%d verifications=%d metadata_latency=%v (simulated 10ms per operation)", got.ID, searches, checks, time.Since(start))
	if err != nil {
		t.Fatal(err)
	}
	if searches != 1 || checks != 1 || got.ID != first.ID {
		t.Fatal("did not stop at first confirmation", got, searches, checks)
	}
}
