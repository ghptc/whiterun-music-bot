func TestFirstConfirmedProgressiveSelection(t *testing.T) {
	track := Track{SpotifyID: "requested", Title: "Song", Artist: "Artist", Artists: []string{"Artist"}, Duration: 210 * time.Second}
	good := Candidate{ID: "abcdefghijk", Title: "Song", Channel: "Artist", Verified: true, Duration: 210}
	for _, tc := range []struct {
		name       string
		first      func(Candidate) Candidate
		wantChecks int
	}{
		{"first confirmed", func(c Candidate) Candidate { return c }, 1},
		{"first uncertain", func(c Candidate) Candidate { c.Duration = 0; return c }, 2},
		{"first wrong", func(c Candidate) Candidate { c.Artist = "Other"; return c }, 2},
		{"plausible high score", func(c Candidate) Candidate { c.Channel = "Archive"; c.Artist = "Artist"; return c }, 2},
		{"same duration cover", func(c Candidate) Candidate { c.Title += " Cover"; return c }, 2},
		{"similar remix", func(c Candidate) Candidate { c.Title += " Remix"; return c }, 2},
	} {
		t.Run(tc.name, func(t *testing.T) {
			second := good
			second.ID = "lmnopqrstuv"
			checks := 0
			got, err := selectSpotify(context.Background(), track, []Candidate{good, second}, func(c Candidate) (Candidate, error) {
				checks++
				if c.ID == good.ID {
					return tc.first(c), nil
				}
				return c, nil
			})
			want := good.ID
			if tc.wantChecks == 2 {
				want = second.ID
			}
			if err != nil || got.ID != want || checks != tc.wantChecks {
				t.Fatalf("selected=%s want=%s checks=%d err=%v", got.ID, want, checks, err)
			}
		})
	}
}

func TestTwoOfficialCompatibleVideosStopAtFirstConfirmation(t *testing.T) {
	track := Track{Title: "Song", Artist: "Artist", Duration: 210 * time.Second}
	a := Candidate{ID: "abcdefghijk", Title: "Song", Channel: "Artist", Verified: true, Duration: 210}
	b := a
	b.ID = "lmnopqrstuv"
	for _, pool := range [][]Candidate{{a, b}, {b, a}} {
		checks := 0
		got, err := selectSpotify(context.Background(), track, pool, func(c Candidate) (Candidate, error) { checks++; return c, nil })
		if err != nil || got.ID != pool[0].ID || checks != 1 {
			t.Fatal(got, err, checks)
		}
	}
}

func TestFirstConfirmationAfterThirteenCandidates(t *testing.T) {
	track := Track{Title: "Song", Artist: "Artist", Duration: 210 * time.Second}
	var pool []Candidate
	for i := 0; i < 13; i++ {
		pool = append(pool, Candidate{ID: fmt.Sprintf("video%06d", i), Title: "Song", Channel: "Artist - Topic", Duration: 210})
	}
	checks, searches := 0, 0
	got, err := discoverSpotify(context.Background(), track, DefaultMatchPolicy(), "query", func(string, string) ([]*Candidate, error) {
		searches++
		var entries []*Candidate
		start, end := 0, 10
		if searches > 1 {
			start, end = 10, len(pool)
		}
		for i := start; i < end; i++ {
			entries = append(entries, &pool[i])
		}
		return entries, nil
	}, func(c Candidate) (Candidate, error) {
		checks++
		if checks < 13 {
			c.Duration = 0
		}
		return c, nil
	})
	if err != nil || checks != 13 || searches != 2 || got.ID != pool[12].ID {
		t.Fatal(got, err, checks)
	}
}

func TestCancellationDuringVerificationCannotPublishConfirmation(t *testing.T) {
	track := Track{Title: "Song", Artist: "Artist", Duration: 210 * time.Second}
	c := Candidate{ID: "abcdefghijk", Title: "Song", Channel: "Artist - Topic", Duration: 210}
	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()
	checks := 0
	_, err := selectSpotify(ctx, track, []Candidate{c, c}, func(c Candidate) (Candidate, error) { checks++; cancel(); return c, nil })
	if !errors.Is(err, context.Canceled) || checks != 1 {
		t.Fatal(err, checks)
	}
}

