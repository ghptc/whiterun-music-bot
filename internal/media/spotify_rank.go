// Spotify scoring is separate from free-text discovery. Scores are ordinal
// ranking weights, not probabilities. Explicit mismatches cannot win on badges.
type spotifyRank struct {
	Title, TitlePrecision, Artist, Credits float64
	DurationDeltaMS                        int64
	SourceClass, Reason                    string
	VersionCompatible                      bool
	NegativeMarkers                        []string
	Score                                  int
}

func normalized(s string) string {
	s = strings.ToLower(norm.NFKD.String(s))
	s = strings.Map(func(r rune) rune {
		if unicode.Is(unicode.Mn, r) || r == '\'' || r == '’' {
			return -1
		}
		return r
	}, s)
	s = strings.TrimSpace(words(s))
	s = strings.NewReplacer(" remastered ", " remaster ", " featuring ", " feat ", " ft ", " feat ").Replace(" " + s + " ")
	return strings.TrimSpace(s)
}
func coverage(want, got string) float64 {
	tokens := semanticTokens(normalized(want))
	if len(tokens) == 0 {
		return 0
	}
	hits := 0
	for _, token := range tokens {
		if has(normalized(got), token) {
			hits++
		}
	}
	return float64(hits) / float64(len(tokens))
}

var featureClause = regexp.MustCompile(`(?i)\s*[\(\[]?\b(?:feat\.?|ft\.?|featuring)\s+[^)\]–—]*[)\]]?`)

func recordingTitle(s string) string {
	parts := strings.Split(s, " - ")
	for i := range parts {
		parts[i] = featureClause.ReplaceAllString(parts[i], " ")
	}
	return strings.Join(parts, " - ")
}

var versionMarkers = []string{"live", "remix", "acoustic", "remaster", "instrumental", "karaoke", "slowed", "reverb", "sped up", "nightcore", "8d", "bass boosted", "cover", "mashup"}

func versionPresent(s, marker string) bool {
	s = normalized(s)
	if marker == "live" {
		return has(s, "live") || has(s, "concert") || has(s, "unplugged")
	}
	if marker == "acoustic" {
		return has(s, "acoustic") || has(s, "unplugged")
	}
	return has(s, marker)
}
func sourceClass(t Track, c Candidate) (string, int) {
	channel := c.Channel
	if channel == "" {
		channel = c.Uploader
	}
	identity := channelIdentity(normalized(channel))
	artist := channelIdentity(normalized(t.Artist))
	same := identity != "" && identity == artist
	if same && c.Verified {
		return "verified_artist", 60
	}
	if same && strings.HasSuffix(strings.TrimSpace(words(channel)), " topic") {
		return "topic", 55
	}
	if same && strings.HasSuffix(strings.ToLower(channel), "vevo") {
		return "artist_vevo", 50
	}
	if same && len(c.Artists) > 0 && c.Track != "" && strings.Contains(c.Description, "Auto-generated by YouTube") {
		return "release", 55
	}
	// Distributor-owned auto-generated releases carry structured recording
	// credits even when the channel is not named after the performing artist.
	if c.Verified && c.Track != "" && c.Album != "" && strings.Contains(c.Description, "Auto-generated by YouTube") {
		for _, credited := range c.Artists {
			if normalized(credited) == normalized(t.Artist) {
				return "release", 55
			}
		}
	}
	if same {
		return "artist_named", 25
	}
	if has(c.Title, "lyric") || has(c.Title, "lyrics") {
		return "lyrics", -10
	}
	return "other", 0
}
func rankSpotify(t Track, c Candidate, provisional bool) spotifyRank {
	return rankSpotifyPolicy(t, c, provisional, DefaultMatchPolicy())
}
func rankSpotifyPolicy(t Track, c Candidate, provisional bool, policy MatchPolicy) spotifyRank {
	b := spotifyRank{Reason: "accepted", VersionCompatible: true}
	reject := func(reason string) spotifyRank { b.Reason = reason; return b }
	if !videoID.MatchString(c.ID) || c.Title == "" || c.Live || c.LiveStatus == "is_live" || c.LiveStatus == "is_upcoming" {
		return reject("not_finite_recording")
	}
	if c.Availability == "private" || c.Availability == "premium_only" || c.Availability == "subscriber_only" {
		return reject("unavailable")
	}
	if t.ISRC != "" && c.ISRC != "" && !strings.EqualFold(t.ISRC, c.ISRC) {
		return reject("isrc_mismatch")
	}
	if t.Explicit != nil && c.Explicit != nil && *t.Explicit != *c.Explicit {
		return reject("explicit_mismatch")
	}
	title := c.Title
	if c.Track != "" {
		title = c.Track
	}
	intended := t.Title + " " + t.Album
	// Remove artist identities before interpreting markers (e.g. 2 Live Crew).
	versionText := normalized(c.Title + " " + c.Track)
	for _, a := range append([]string{t.Artist}, t.Artists...) {
		if a != "" {
			versionText = strings.ReplaceAll(" "+versionText+" ", " "+normalized(a)+" ", " ")
		}
	}
	for _, marker := range versionMarkers {
		if versionPresent(intended, marker) != versionPresent(versionText+" "+c.Album, marker) {
			b.VersionCompatible = false
			b.NegativeMarkers = append(b.NegativeMarkers, marker)
		}
	}
	for _, marker := range []string{"reaction", "reacts", "tutorial", "interview", "full album", "compilation", "documentary", "medley", "extended", "edit"} {
		if has(versionText, marker) && !has(normalized(t.Title), marker) {
			b.NegativeMarkers = append(b.NegativeMarkers, marker)
		}
	}
	if len(b.NegativeMarkers) > 0 {
		return reject("version_or_semantic_mismatch")
	}
	b.Title = coverage(recordingTitle(t.Title), title)
	// Matching all requested words is insufficient: a concert venue, medley,
	// or another song appended to the title must not pass as the recording.
	candidateTitle := " " + normalized(recordingTitle(c.Title)) + " "
	for _, artist := range append([]string{t.Artist}, t.Artists...) {
		if artist != "" {
			candidateTitle = strings.ReplaceAll(candidateTitle, " "+normalized(artist)+" ", " ")
		}
	}
	for _, word := range []string{"hq", "visualizer", "visualiser", "lyric", "only"} {
		candidateTitle = strings.ReplaceAll(candidateTitle, " "+word+" ", " ")
	}
	b.TitlePrecision = coverage(candidateTitle, recordingTitle(t.Title))
	if b.TitlePrecision < policy.MinTitlePrecision {
		return reject("extra_title_content")
	}
	if b.Title < 1 {
		return reject("title_mismatch")
	}
	artists := strings.Join(c.Artists, " ")
	if artists == "" {
		artists = c.Artist
	}
	artistEvidence := artists
	if artistEvidence == "" {
		artistEvidence = c.Channel + " " + c.Uploader + " " + c.Title
	}
	b.Artist = coverage(t.Artist, artistEvidence)
	if artists == "" {
		b.Artist = 0
		if channelIdentity(normalized(c.Channel)) == channelIdentity(normalized(t.Artist)) || channelIdentity(normalized(c.Uploader)) == channelIdentity(normalized(t.Artist)) {
			b.Artist = 1
		}
		for _, separator := range []string{" - ", " — ", " – "} {
			if prefix, _, ok := strings.Cut(c.Title, separator); ok && normalized(recordingTitle(prefix)) == normalized(t.Artist) {
				b.Artist = 1
			}
		}
	}
	if artists != "" {
		b.Artist = 0
		actualArtists := c.Artists
		if len(actualArtists) == 0 {
			actualArtists = []string{c.Artist}
		}
		for _, actual := range actualArtists {
			if normalized(actual) == normalized(t.Artist) {
				b.Artist = 1
			}
		}
	}
	if channelIdentity(normalized(c.Channel)) == channelIdentity(normalized(t.Artist)) && t.Artist != "" && artists == "" {
		b.Artist = 1
	}
	if provisional && artists == "" && (c.MusicSearch || c.Channel == "" && c.Uploader == "") {
		b.Artist = 1
	} // unknown, MUST verify
	if b.Artist < 1 {
		return reject("primary_artist_mismatch")
	}
	credited := t.Artists
	if len(credited) == 0 {
		credited = []string{t.Artist}
	}
	if !provisional && len(credited) > 1 && len(c.Artists) == 0 {
		return reject("credits_unknown")
	}
	for _, artist := range credited {
		evidence := coverage(artist, artistEvidence+" "+c.Title)
		if len(c.Artists) > 0 {
			evidence = 0
			for _, actual := range c.Artists {
				if normalized(actual) == normalized(artist) {
					evidence = 1
					break
				}
			}
		}
		b.Credits += evidence
	}
	b.Credits /= float64(len(credited))
	// Explicit recording credits must not contradict the requested collaborators.
	if (!provisional || artists != "") && b.Credits < 1 {
		return reject("credited_artist_mismatch")
	}
	durationScore := 0
	if t.Duration > 0 {
		if c.Duration <= 0 {
			if !provisional {
				return reject("duration_unknown")
			}
		} else {
			delta := math.Abs(c.Duration - t.Duration.Seconds())
			b.DurationDeltaMS = int64(delta * 1000)
			if delta > math.Max(policy.MaxDurationDelta.Seconds(), t.Duration.Seconds()*policy.MaxDurationFraction) {
				return reject("duration_mismatch")
			}
			durationScore = max(0, 80-int(delta*4))
		}
	} else if c.Duration > 20*60 {
		return reject("excessive_duration")
	}
	bonus := 0
	b.SourceClass, bonus = sourceClass(t, c)
	b.Score = int(b.Title*400+b.Artist*200+b.Credits*100-(1-b.TitlePrecision)*100) + durationScore + bonus
	if provisional && c.MusicSearch {
		b.Score += 50
	}
	if b.Score < policy.MinScore {
		return reject("below_match_floor")
	}
	return b
}

func deduplicateCandidates(pools ...[]*Candidate) []Candidate {
	var result []Candidate
	seen := map[string]int{}
	for _, pool := range pools {
		for _, ptr := range pool {
			if ptr == nil || !videoID.MatchString(ptr.ID) {
				continue
			}
			c := *ptr
			if i, ok := seen[c.ID]; ok {
				// Normal search supplies richer flat metadata; preserve music discovery signal.
				music := result[i].MusicSearch || c.MusicSearch
				if c.Channel != "" || c.Duration > 0 {
					result[i] = c
				}
				result[i].MusicSearch = music
			} else {
				seen[c.ID] = len(result)
				result = append(result, c)
			}
		}
	}
	return result
}
func (r Resolver) resolveSpotify(ctx context.Context, query string) (Candidate, error) {
	key := mappingKey(*r.Match, r.matchPolicy())
	if r.Mappings != nil {
		cached, ok, err := r.Mappings.LoadMapping(ctx, key)
		if err != nil {
			return Candidate{}, err
		}
		if ok {
			full, err := r.extract(ctx, "https://www.youtube.com/watch?v="+cached.ID, "spotify_mapping_revalidation", false)
			if err != nil {
				return Candidate{}, err
			}
			if full.ID == cached.ID && CompareSpotify(*r.Match, full.Candidate, r.matchPolicy()).Status == MatchConfirmed {
				return full.Candidate, nil
			}
			if err := r.Mappings.DeleteMapping(ctx, key); err != nil {
				return Candidate{}, err
			}
			if ctx.Err() != nil {
				return Candidate{}, ctx.Err()
			}
		}
	}

	chosen, err := discoverSpotify(ctx, *r.Match, r.matchPolicy(), query,
		func(target, purpose string) ([]*Candidate, error) {
			attempt, cancel := context.WithTimeout(ctx, 15*time.Second)
			defer cancel()
			result, err := r.extract(attempt, target, purpose, true)
			return result.Entries, err
		}, func(c Candidate) (Candidate, error) {
			attempt, cancel := context.WithTimeout(ctx, 15*time.Second)
			defer cancel()
			full, err := r.extract(attempt, "https://www.youtube.com/watch?v="+c.ID, "spotify_candidate_verification", false)
			if err == nil && full.ID != c.ID {
				err = errors.New("YouTube returned a different video ID")
			}
			return full.Candidate, err
		})
	if err == nil && r.Mappings != nil {
		if saveErr := r.Mappings.SaveMapping(ctx, key, chosen); saveErr != nil {
			return Candidate{}, saveErr
		}
	}
	return chosen, err
}
func selectSpotify(ctx context.Context, track Track, candidates []Candidate, verify func(Candidate) (Candidate, error)) (Candidate, error) {
	return selectSpotifyPolicy(ctx, track, DefaultMatchPolicy(), candidates, verify)
}
func selectSpotifyPolicy(ctx context.Context, track Track, policy MatchPolicy, candidates []Candidate, verify func(Candidate) (Candidate, error)) (Candidate, error) {
	if err := policy.Validate(); err != nil {
		return Candidate{}, err
	}
	type rankedCandidate struct {
		candidate Candidate
		rank      spotifyRank
	}
	var shortlist []rankedCandidate
	timing := TimingFrom(ctx)
	logRank := func(c Candidate, b spotifyRank, stage string) {
		if timing != nil {
			timing.log.InfoContext(ctx, "spotify_candidate", "spotify_track_id", track.SpotifyID, "video_id", c.ID, "candidate_title", c.Title, "recording_title", c.Track, "recording_artists", c.Artists, "recording_album", c.Album, "duration_seconds", c.Duration, "recording_isrc", c.ISRC, "channel_id", c.ChannelID, "channel_verified", c.Verified, "stage", stage, "title_similarity", b.Title, "title_precision", b.TitlePrecision, "artist_similarity", b.Artist, "credited_artist_similarity", b.Credits, "duration_delta_ms", b.DurationDeltaMS, "source_class", b.SourceClass, "version_compatible", b.VersionCompatible, "negative_markers", b.NegativeMarkers, "ranking_score", b.Score, "reason", b.Reason)
		}
	}
	for _, c := range candidates {
		b := rankSpotifyPolicy(track, c, true, policy)
		logRank(c, b, "discovery")
		if b.Reason == "accepted" {
			shortlist = append(shortlist, rankedCandidate{c, b})
		}
	}
	sort.SliceStable(shortlist, func(i, j int) bool { return shortlist[i].rank.Score > shortlist[j].rank.Score })
	var accepted []rankedCandidate
	sawUncertain := false
	var verificationErrors []error
	// Sparse Music summaries must get a verification opportunity even when
	// normal search has many richly described but noncanonical reuploads.
	var selected []rankedCandidate
	used := map[string]bool{}
	for _, music := range []bool{true, false} {
		count := 0
		for _, candidate := range shortlist {
			if candidate.candidate.MusicSearch == music && count < 2 {
				selected = append(selected, candidate)
				used[candidate.candidate.ID] = true
				count++
			}
		}
	}
	for _, candidate := range shortlist {
		if len(selected) < 4 && !used[candidate.candidate.ID] {
			selected = append(selected, candidate)
			used[candidate.candidate.ID] = true
		}
	}
	for _, item := range selected {
		if ctx.Err() != nil {
			return Candidate{}, ctx.Err()
		}
		full, err := verify(item.candidate)
		if err != nil {
			timing.Event("spotify_candidate_verification_failed", time.Now(), "spotify_track_id", track.SpotifyID, "video_id", item.candidate.ID, "reason", "verification_failed")
			verificationErrors = append(verificationErrors, err)
			continue
		}
		b := rankSpotifyPolicy(track, full, false, policy)
		if CompareSpotify(track, full, policy).Status == MatchUncertain {
			sawUncertain = true
		}
		logRank(full, b, "verified")
		if b.Reason == "accepted" {
			accepted = append(accepted, rankedCandidate{full, b})
		}
	}
	if ctx.Err() != nil {
		return Candidate{}, ctx.Err()
	}
	if len(verificationErrors) > 0 {
		return Candidate{}, fmt.Errorf("candidate verification infrastructure failed: %w", errors.Join(verificationErrors...))
	}
	if len(accepted) == 0 {
		if sawUncertain {
			return Candidate{}, &MatchError{Status: MatchUncertain, Reason: "insufficient_metadata"}
		}
		return Candidate{}, &MatchError{Status: MatchRejected, Reason: "no_acceptable_candidate"}
	}
	// Complete-link grouping prevents A~B~C from hiding an A/C contradiction.
	sort.Slice(accepted, func(i, j int) bool {
		if accepted[i].rank.Score == accepted[j].rank.Score {
			return accepted[i].candidate.ID < accepted[j].candidate.ID
		}
		return accepted[i].rank.Score > accepted[j].rank.Score
	})
	var groups [][]rankedCandidate
	for _, candidate := range accepted {
		placed := false
		for gi, group := range groups {
			compatible := true
			for _, member := range group {
				if recordingEquivalence(track, candidate.candidate, member.candidate) == "" {
					compatible = false
					break
				}
			}
			if compatible {
				groups[gi] = append(groups[gi], candidate)
				placed = true
				break
			}
		}
		if !placed {
			groups = append(groups, []rankedCandidate{candidate})
		}
	}
	best, bestRank, bestScore := groups[0][0].candidate, groups[0][0].rank, groups[0][0].rank.Score
	runnerUp := -1
	if len(groups) > 1 {
		runnerUp = groups[1][0].rank.Score
	}

	for gi, group := range groups {
		ids := make([]string, 0, len(group))
		evidence := []string{}
		for _, member := range group {
			ids = append(ids, member.candidate.ID)
			if member.candidate.ID != group[0].candidate.ID {
				evidence = append(evidence, recordingEquivalence(track, group[0].candidate, member.candidate))
			}
		}
		timing.Event("spotify_recording_group", time.Now(), "spotify_track_id", track.SpotifyID, "group", gi, "video_ids", ids, "evidence", evidence)
	}
	// Prefer a uniquely identified requested release without merging unrelated
	// uploads. Two conflicting release groups remain uncertain regardless of score.
	releaseGroup := -1
	var releaseCandidate Candidate
	for gi, group := range groups {
		for _, member := range group {
			if exactRequestedRelease(track, member.candidate) {
				if releaseGroup >= 0 && releaseGroup != gi {
					return Candidate{}, &MatchError{Status: MatchUncertain, Reason: "conflicting_release_identity"}
				}
				if releaseGroup < 0 {
					releaseCandidate = member.candidate
				}
				releaseGroup = gi
			}
		}
	}
	if releaseGroup >= 0 {
		timing.Event("spotify_release_selected", time.Now(), "spotify_track_id", track.SpotifyID, "video_id", releaseCandidate.ID, "evidence", "exact_requested_release", "groups", len(groups))
		return releaseCandidate, nil
	}
	if runnerUp >= 0 && bestScore-runnerUp < policy.MinScoreMargin {
		timing.Event("spotify_recording_ambiguous", time.Now(), "spotify_track_id", track.SpotifyID, "reason", "ambiguous_candidates", "groups", len(groups))
		return Candidate{}, &MatchError{Status: MatchUncertain, Reason: "ambiguous_candidates"}
	}
	timing.Event("spotify_recording_selected", time.Now(), "spotify_track_id", track.SpotifyID, "video_id", best.ID, "source_class", bestRank.SourceClass, "duration_delta_ms", bestRank.DurationDeltaMS, "ranking_score", bestRank.Score)
	return best, nil
}
