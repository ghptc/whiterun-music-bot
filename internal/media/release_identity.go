package media

import (
	"math"
	"slices"
	"strings"
)

// exactRequestedRelease identifies a release, not equivalence between uploads.
// Generic official videos must not veto an independently identified release.
// This is metadata corroboration; it does not claim acoustic identity.
func exactRequestedRelease(t Track, c Candidate) bool {
	if rankSpotify(t, c, false).Reason != "accepted" {
		return false
	}
	class, _ := sourceClass(t, c)
	if class != "verified_artist" && class != "topic" && class != "artist_vevo" && class != "release" {
		return false
	}
	if t.Duration <= 0 || c.Duration <= 0 || math.Abs(t.Duration.Seconds()-c.Duration) > 2 {
		return false
	}
	if validISRC.MatchString(strings.ToUpper(t.ISRC)) && strings.EqualFold(t.ISRC, c.ISRC) {
		return true
	}
	if versionPresent(t.Title+" "+t.Album, "remaster") || t.Album == "" || normalized(c.Album) != normalized(t.Album) || normalized(recordingTitle(c.Track)) != normalized(recordingTitle(t.Title)) {
		return false
	}
	if !strings.Contains(c.Description, "Auto-generated by YouTube") {
		return false
	}
	credits := func(v []string) []string {
		out := make([]string, len(v))
		for i, s := range v {
			out[i] = normalized(s)
		}
		slices.Sort(out)
		return slices.Compact(out)
	}
	wanted := t.Artists
	if len(wanted) == 0 {
		wanted = []string{t.Artist}
	}
	return slices.Equal(credits(wanted), credits(c.Artists))
}
