import (
	"context"
	"testing"
	"time"
)

func TestRequestedReleaseSelectionDoesNotAssertUploadEquivalence(t *testing.T) {
	tr := Track{Title: "Song", Artist: "Artist", Artists: []string{"Artist"}, Album: "Album", Duration: 210 * time.Second}
	release := Candidate{ID: "abcdefghijk", Title: "Song", Track: "Song", Artists: []string{"Artist"}, Album: "Album", Duration: 210, Channel: "Distributor", Verified: true, Description: "Provided to YouTube by Label\nAuto-generated by YouTube."}
	generic := Candidate{ID: "lmnopqrstuv", Title: "Artist - Song", Channel: "Artist", Verified: true, Duration: 210}
	if recordingEquivalence(tr, release, generic) != "" {
		t.Fatal("invented upload equivalence")
	}
	for _, pool := range [][]Candidate{{generic, release}, {release, generic}} {
		got, err := selectSpotify(context.Background(), tr, pool, func(c Candidate) (Candidate, error) { return c, nil })
		if err != nil || got.ID != pool[0].ID {
			t.Fatal(got, err)
		}
	}
	for _, tc := range []struct {
		name   string
		mutate func(*Candidate)
	}{
		{"copied unverified metadata", func(c *Candidate) { c.Verified = false }},
		{"different album", func(c *Candidate) { c.Album = "Other" }},
		{"different credits", func(c *Candidate) { c.Artists = []string{"Artist", "Other"} }},
		{"different edit", func(c *Candidate) { c.Title = "Song (Live)"; c.Track = c.Title }},
		{"substantial duration difference", func(c *Candidate) { c.Duration = 214 }},
	} {
		t.Run(tc.name, func(t *testing.T) {
			c := release
			tc.mutate(&c)
			if exactRequestedRelease(tr, c) {
				t.Fatal("unreliable release identity")
			}
		})
	}
	other := release
	other.ID = "zzzzzzzzzzz"
	other.ISRC = "USAAA1200002"
	release.ISRC = "USAAA1200001"
	tr.ISRC = release.ISRC
	got, err := selectSpotify(context.Background(), tr, []Candidate{other, release}, func(c Candidate) (Candidate, error) { return c, nil })
	if err != nil || got.ID != release.ID {
		t.Fatal("requested ISRC not enforced", got, err)
	}
}

func TestMusicDistributorSummaryMustBeVerified(t *testing.T) {
	tr := Track{Title: "Bring The Noise Remix - Pumpkin Edit", Artist: "Public Enemy", Artists: []string{"Public Enemy", "Benny Benassi"}, Duration: 217 * time.Second}
	c := Candidate{ID: "abcdefghijk", Title: "Bring The Noise Remix (Pumpkin Edit)", Channel: "Channel ZERO", Duration: 218, MusicSearch: true}
	if rankSpotify(tr, c, true).Reason != "accepted" {
		t.Fatal("summary prematurely rejected")
	}
	if CompareSpotify(tr, c, DefaultMatchPolicy()).Status == MatchConfirmed {
		t.Fatal("summary accepted without credits")
	}
	for _, title := range []string{"Bring The Noise (Live)", "Bring The Noise Remix (Sfaction Remix)", "Bring The Noise Remix (Pumpkin Instrumental)", "Bring The Noise Remix (Pumpkin Edit) Cover"} {
		c.Title = title
		if rankSpotify(tr, c, true).Reason == "accepted" {
			t.Fatalf("accepted incompatible version %s", title)
		}
	}
}
