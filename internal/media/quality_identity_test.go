func qualityIdentity() (Track, Candidate) {
	return Track{Title: "Song", Artist: "Artist", Artists: []string{"Artist"}, Album: "Album", Duration: 210 * time.Second, ISRC: "USAAA1200001", Explicit: new(true)},
		Candidate{ID: "abcdefghijk", Title: "Song", Track: "Song", Artist: "Artist", Artists: []string{"Artist"}, Album: "Album", Channel: "Artist", Verified: true, Duration: 210, ISRC: "USAAA1200001", Explicit: new(true)}
}
func TestQualityIdentityMatrix(t *testing.T) {
	// Test versions against three independent forms of authority. Provenance
	// must never override a contradiction in recording identity.
	for _, source := range []string{"isrc", "verified", "distributor"} {
		for _, variant := range []string{"Live", "Acoustic", "Instrumental", "Karaoke", "Cover", "Remix", "Remastered 2020", "Radio Edit", "Extended Mix", "Sped Up", "Slowed"} {
			t.Run(source+"/"+variant, func(t *testing.T) {
				tr, c := qualityIdentity()
				switch source {
				case "verified":
					tr.ISRC = ""
					c.ISRC = ""
				case "distributor":
					tr.ISRC = ""
					c.ISRC = ""
					c.Channel = "Distributor"
					c.Description = "Provided to YouTube by Label\nAuto-generated by YouTube."
				}
				c.Title += " (" + variant + ")"
				c.Track = c.Title
				got := CompareSpotify(tr, c, DefaultMatchPolicy())
				if got.Status != MatchRejected {
					t.Fatalf("incompatible recording confirmed: %+v", got)
				}
			})
		}
	}
	for _, tc := range []struct {
		name   string
		change func(*Track, *Candidate)
		want   MatchStatus
	}{
		{"original", func(*Track, *Candidate) {}, MatchConfirmed},
		{"wrong ISRC", func(_ *Track, c *Candidate) { c.ISRC = "USAAA1200002" }, MatchRejected},
		{"explicit to clean", func(_ *Track, c *Candidate) { c.Explicit = new(false) }, MatchRejected},
		{"clean to explicit", func(tr *Track, _ *Candidate) { tr.Explicit = new(false) }, MatchRejected},
		{"duration far", func(_ *Track, c *Candidate) { c.Duration = 350 }, MatchRejected},
		{"duration absent", func(_ *Track, c *Candidate) { c.Duration = 0 }, MatchUncertain},
		{"homonymous artist", func(_ *Track, c *Candidate) { c.Artist = "Other"; c.Artists = []string{"Other"}; c.Channel = "Other" }, MatchRejected},
		{"missing guest", func(tr *Track, _ *Candidate) { tr.Artists = append(tr.Artists, "Guest") }, MatchRejected},
		{"no provenance", func(tr *Track, c *Candidate) { tr.ISRC = ""; c.ISRC = ""; c.Channel = "Archive"; c.Verified = false }, MatchUncertain},
		{"official duplicated", func(_ *Track, c *Candidate) { c.ID = "lmnopqrstuv" }, MatchConfirmed},
	} {
		t.Run(tc.name, func(t *testing.T) {
			tr, c := qualityIdentity()
			tc.change(&tr, &c)
			if got := CompareSpotify(tr, c, DefaultMatchPolicy()); got.Status != tc.want {
				t.Fatalf("got %+v want %s", got, tc.want)
			}
		})
	}
}
func TestQualityFirstConfirmed(t *testing.T) {
	for _, badBefore := range []int{0, 1, 2, 3} {
		t.Run(fmt.Sprint(badBefore), func(t *testing.T) {
			tr, confirmed := qualityIdentity()
			pool := []Candidate{}
			for i := range badBefore {
				c := confirmed
				c.ID = fmt.Sprintf("bad%08d", i)
				c.Title = "Song (Live)"
				c.Track = c.Title
				pool = append(pool, c)
			}
			pool = append(pool, confirmed)
			later := confirmed
			later.ID = "lmnopqrstuv"
			pool = append(pool, later)
			verified := map[string]bool{}
			got, err := selectSpotify(context.Background(), tr, pool, func(c Candidate) (Candidate, error) {
				if c.ID == later.ID {
					t.Fatal("verified a candidate after confirmation")
				}
				verified[c.ID] = true
				return c, nil
			})
			if err != nil || got.ID != confirmed.ID || !verified[confirmed.ID] {
				t.Fatalf("got=%+v err=%v", got, err)
			}
		})
	}
}
func TestQualityCacheBoundaries(t *testing.T) {
	now := time.Unix(1700000000, 0)
	for _, tc := range []struct {
		name  string
		delta time.Duration
		hit   bool
	}{
		{"before expiry", searchCacheTTL - time.Nanosecond, true},
		{"exact expiry", searchCacheTTL, false},
		{"after expiry", searchCacheTTL + time.Nanosecond, false},
	} {
		t.Run(tc.name, func(t *testing.T) {
			cache := &SearchCache{}
			tr, _ := qualityIdentity()
			cache.put("song", tr, now)
			got, hit := cache.get("song", now.Add(tc.delta))
			if hit != tc.hit {
				t.Fatalf("hit=%v want %v", hit, tc.hit)
			}
			if hit {
				got.Artists[0] = "changed"
				*got.Explicit = false
				again, _ := cache.get("song", now)
				if again.Artists[0] != "Artist" || !*again.Explicit {
					t.Fatal("shared mutable metadata")
				}
			}
			if !hit && len(cache.entries) != 0 {
				t.Fatal("expired entry not invalidated")
			}
		})
	}
	t.Run("evicts oldest without losing newer entries", func(t *testing.T) {
		cache := &SearchCache{}
		for i := 0; i <= searchCacheLimit; i++ {
			cache.put(fmt.Sprint(i), Track{Title: fmt.Sprint(i)}, now.Add(time.Duration(i)*time.Millisecond))
		}
		if len(cache.entries) != searchCacheLimit {
			t.Fatal(len(cache.entries))
		}
		if _, hit := cache.get("0", now.Add(time.Second)); hit {
			t.Fatal("oldest entry retained")
		}
		for i := 1; i <= searchCacheLimit; i++ {
			if tr, hit := cache.get(fmt.Sprint(i), now.Add(time.Second)); !hit || tr.Title != fmt.Sprint(i) {
				t.Fatal("new entry lost", i)
			}
		}
	})
}

// A blanket rejection of every named version would have perfect negative
// precision while refusing valid requests. Exercise matching named recordings.
func TestQualityRequestedVersions(t *testing.T) {
	for _, version := range []string{"Live", "Acoustic", "Instrumental", "Karaoke", "Cover", "Remix", "Radio Edit", "Extended Mix", "Sped Up", "Slowed"} {
		t.Run(version, func(t *testing.T) {
			tr, c := qualityIdentity()
			tr.Title += " (" + version + ")"
			c.Title = tr.Title
			c.Track = tr.Title
			if got := CompareSpotify(tr, c, DefaultMatchPolicy()); got.Status != MatchConfirmed {
				t.Fatalf("requested recording refused: %+v", got)
			}
		})
	}
}

func TestQualityIdentityMatrixVersionIndependentOfTitlePrecision(t *testing.T) {
	for _, location := range []string{"title", "album"} {
		for _, version := range []string{"Live", "Remix", "Acoustic", "Instrumental", "Karaoke", "Cover", "Remastered 2020", "Slowed", "Sped Up"} {
			t.Run(location+"/"+version, func(t *testing.T) {
				tr, c := qualityIdentity()
				tr.Title = "The Long Road Through Winter Mountains"
				c.Title = tr.Title
				c.Track = tr.Title
				if location == "title" {
					c.Title += " (" + version + ")"
					c.Track = c.Title
				} else {
					c.Album += " (" + version + ")"
				}
				if got := CompareSpotify(tr, c, DefaultMatchPolicy()); got.Status != MatchRejected || got.Reason != "version_or_semantic_mismatch" {
					t.Fatalf("version guard bypassed: %+v", got)
				}
			})
		}
	}
}

func TestQualityCacheInvalidation(t *testing.T) {
	for _, source := range []string{"spotify", "youtube"} {
		t.Run(source, func(t *testing.T) {
			tr, _ := qualityIdentity()
			tr.RequestedSource = source
			cache := &SearchCache{}
			key := "spotify:" + MappingKey(tr, nil)
			now := time.Now()
			cache.put(key, tr, now)
			cache.put("unrelated", Track{Title: "retained"}, now)
			ctx, cancel := context.WithCancel(context.Background())
			cancel()
			(Resolver{Cache: cache}).InvalidateSpotify(ctx, tr)
			_, hit := cache.get(key, now)
			if hit != (source != "spotify") {
				t.Fatal("wrong invalidation scope", hit)
			}
			if got, hit := cache.get("unrelated", now); !hit || got.Title != "retained" {
				t.Fatal("unrelated entry invalidated")
			}
		})
	}
}
